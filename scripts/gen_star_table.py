#!/usr/bin/env python3
"""Write a Rust table of the brightest stars from a catalogue in the Bright Star Catalogue's fixed
columns (J2000 position, proper motion, magnitude), naming its source at the top of the table.

    python3 scripts/gen_star_table.py <catalog file> <how many> <source line> <out.rs>

A record with no J2000 position or no magnitude has nothing to draw and is left out; anything else
that does not read stops the run. Fewer readable records than asked for, or none, stops it too.

Author: Moroya Sakamoto
"""

import math
import sys

# 1-based inclusive columns, as a catalogue's byte-by-byte description gives them
RAH, RAM, RAS = (76, 77), (78, 79), (80, 83)
DESIGN, DED, DEM, DES = (84, 84), (85, 86), (87, 88), (89, 90)
VMAG = (103, 107)
PM_RA, PM_DEC = (149, 154), (155, 160)
ARCSEC = math.pi / 180 / 3600


def field(line, cols):
    return line[cols[0] - 1 : cols[1]].strip()


def read(line):
    """(ra, dec, pm_ra, pm_dec, mag) in radians, radians per year, or None with nothing to draw"""
    if not field(line, RAH) or not field(line, VMAG):
        return None
    ra = (int(field(line, RAH)) + int(field(line, RAM)) / 60 + float(field(line, RAS)) / 3600) * math.pi / 12
    sign = {"+": 1, "-": -1}[field(line, DESIGN)]
    dec = sign * (int(field(line, DED)) + int(field(line, DEM)) / 60 + int(field(line, DES)) / 3600) * math.pi / 180
    pm = lambda cols: float(field(line, cols)) * ARCSEC if field(line, cols) else 0.0
    return ra, dec, pm(PM_RA), pm(PM_DEC), float(field(line, VMAG))


def brightest(lines, count):
    stars = [s for s in map(read, lines) if s is not None]
    if count <= 0 or len(stars) < count:
        raise ValueError(f"{len(stars)} stars read, {count} asked for")
    # by magnitude, then position, so the same file always gives the same table
    return sorted(stars, key=lambda s: (s[4], s[0], s[1]))[:count]


def table(stars, source):
    rows = "".join(
        f"    Star {{ ra: {r!r}, dec: {d!r}, pm_ra: {a!r}, pm_dec: {b!r}, mag: {m!r} }},\n" for r, d, a, b, m in stars
    )
    return (
        "// Generated by scripts/gen_star_table.py. Do not edit.\n"
        f"// Source: {source}\n"
        "use crate::stars::Star;\n\n"
        f"/// The {len(stars)} brightest stars\n"
        "#[rustfmt::skip]\n"
        f"pub const BRIGHTEST: [Star; {len(stars)}] = [\n{rows}];\n"
    )


def main(argv):
    if len(argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    path, count, source, out = argv
    if not source.strip():
        print("a table must name its source", file=sys.stderr)
        return 2
    with open(path, encoding="latin-1") as f:
        stars = brightest(f.read().splitlines(), int(count))
    with open(out, "w", encoding="utf-8") as f:
        f.write(table(stars, source))
    print(f"wrote {len(stars)} stars to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
