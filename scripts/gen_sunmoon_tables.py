#!/usr/bin/env python3
"""Generate src/sunmoon_table.rs from ERFA's epv00.c and moon98.c.

The Earth ephemeris (a simplified solution from VSOP2000: harmonic terms for
the Sun-to-Earth and barycentre-to-Sun vectors, powers 0 to 2 of time) and the
Moon series (Meeus 1998, chapter 47: 60 longitude/distance and 60 latitude
terms) are copied from ERFA v2.0.1 `src/epv00.c` and `src/moon98.c`
(BSD-3-Clause, see THIRD-PARTY-NOTICES). The decimal literals are copied
character for character, so each Rust literal parses to the same double as the
C one.

Usage:
    python3 scripts/gen_sunmoon_tables.py <epv00.c> <moon98.c>          # write
    python3 scripts/gen_sunmoon_tables.py <epv00.c> <moon98.c> --check  # compare

Fetch the sources with:
    curl -O https://raw.githubusercontent.com/liberfa/erfa/v2.0.1/src/epv00.c
    curl -O https://raw.githubusercontent.com/liberfa/erfa/v2.0.1/src/moon98.c
"""

import hashlib
import pathlib
import re
import sys

ERFA_TAG = "v2.0.1"
ERFA_COMMIT = "9915ba38c9365f8b0738269b8c2ac1fdd5f8dee3"
EPV00_SHA256 = "4568b28026cd83800b4a4f66d44f8f3451d7306f1c3fcf7e4cd6bfeb206dde57"
MOON98_SHA256 = "8633f78b8ec33132743596700fd3ecfbb2ebcb4e886894e377556de9655d1237"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "sunmoon_table.rs"
EPV_ARRAYS = [f"{m}{p}{c}" for m in "es" for p in "012" for c in "xyz"]
# terms per array in ERFA v2.0.1 (a changed source changes these and is refused)
EPV_COUNTS = {
    "e0x": 501, "e0y": 501, "e0z": 137, "e1x": 79, "e1y": 80, "e1z": 12,
    "e2x": 5, "e2y": 5, "e2z": 3, "s0x": 212, "s0y": 213, "s0z": 69,
    "s1x": 50, "s1y": 50, "s1z": 14, "s2x": 9, "s2y": 9, "s2z": 2,
}
MOON_COUNTS = {"tlr": 60, "tb": 60}
NUM = r"[-+]?[0-9]+\.[0-9]*(?:[eE][-+]?[0-9]+)?"


def source(path: str, pin: str) -> str:
    data = pathlib.Path(path).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != pin:
        sys.exit(f"{path}: sha256 {digest} != pinned {pin}")
    return data.decode("utf-8")


def block(text: str, opener: str) -> str:
    start = text.index(opener)
    return text[start + len(opener):text.index("};", start)]


def lit(s: str) -> str:
    s = s.strip()
    if not re.fullmatch(NUM, s):
        sys.exit(f"unexpected literal {s}")
    return s


def render(epv00: str, moon98: str) -> str:
    epv = {}
    for name in EPV_ARRAYS:
        nums = re.findall(NUM, block(epv00, f"static const double {name}[] = {{"))
        if len(nums) % 3:
            sys.exit(f"{name}: {len(nums)} numbers, not a multiple of 3")
        epv[name] = [nums[i:i + 3] for i in range(0, len(nums), 3)]
    tlr = re.findall(r"\{([^{}]*)\}", block(moon98, "static struct termlr tlr[] = {"))
    tb = re.findall(r"\{([^{}]*)\}", block(moon98, "static struct termb tb[] = {"))
    found = {n: len(v) for n, v in epv.items()}
    if found != EPV_COUNTS or {"tlr": len(tlr), "tb": len(tb)} != MOON_COUNTS:
        sys.exit(f"found {found}, tlr {len(tlr)}, tb {len(tb)}; expected {EPV_COUNTS} and {MOON_COUNTS}")
    out = [
        "// @generated by scripts/gen_sunmoon_tables.py — do not edit by hand.",
        "//",
        f"// Source: ERFA {ERFA_TAG} (commit {ERFA_COMMIT}) src/epv00.c",
        f"// (sha256 {EPV00_SHA256}) and src/moon98.c",
        f"// (sha256 {MOON98_SHA256}).",
        "// Copyright (C) 2013-2023, NumFOCUS Foundation. BSD-3-Clause; the licence",
        "// text is reproduced in THIRD-PARTY-NOTICES. The values are the simplified",
        "// VSOP2000 Earth solution (Moisson & Bretagnon 2001) of ERFA's eraEpv00 and the",
        "// Moon series of Meeus (1998, chapter 47) as in ERFA's eraMoon98.",
    ]
    for name in EPV_ARRAYS:
        model = "Sun-to-Earth" if name[0] == "e" else "Barycentre-to-Sun"
        out += [
            "",
            f"/// {model}, component {name[2]}, terms multiplied by T^{name[1]} (T in Julian",
            "/// years of TDB since J2000.0): amplitude (au), phase (rad), frequency (rad/yr).",
            "#[rustfmt::skip]",
            f"pub(crate) static {name.upper()}: [[f64; 3]; {len(epv[name])}] = [",
        ]
        for a, b, c in epv[name]:
            out.append(f"    [{lit(a)}, {lit(b)}, {lit(c)}],")
        out.append("];")
    out += [
        "",
        "/// Moon longitude and distance: multiples of D, M, M′, F, then the sine",
        "/// coefficient of longitude (deg) and the cosine coefficient of distance (m).",
        "#[rustfmt::skip]",
        f"pub(crate) static MOON_LR: [([i8; 4], f64, f64); {len(tlr)}] = [",
    ]
    for row in tlr:
        f = [x.strip() for x in row.split(",")]
        out.append(f"    ([{', '.join(str(int(x)) for x in f[:4])}], {lit(f[4])}, {lit(f[5])}),")
    out += [
        "];",
        "",
        "/// Moon latitude: multiples of D, M, M′, F, then the sine coefficient (deg).",
        "#[rustfmt::skip]",
        f"pub(crate) static MOON_B: [([i8; 4], f64); {len(tb)}] = [",
    ]
    for row in tb:
        f = [x.strip() for x in row.split(",")]
        out.append(f"    ([{', '.join(str(int(x)) for x in f[:4])}], {lit(f[4])}),")
    out.append("];")
    return "\n".join(out) + "\n"


def main() -> None:
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    rendered = render(source(sys.argv[1], EPV00_SHA256), source(sys.argv[2], MOON98_SHA256))
    if "--check" in sys.argv[3:]:
        if OUT.read_text(encoding="utf-8") != rendered:
            sys.exit(f"{OUT} differs from the generator output")
        print(f"{OUT.name}: identical")
    else:
        OUT.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
