#!/usr/bin/env python3
"""Generate tests/golden/cio.csv and tests/golden/cio_args.csv: IAU 2006/2000A
precession-nutation, the CIO locator s and the celestial-to-terrestrial
matrix as ERFA 2.0.1 computes them, and the arguments of the series.

None of the expected values comes from this crate. Every value written is the
same on every machine: ERFA's expressions evaluated one IEEE binary64
operation at a time with correctly rounded sines, cosines and arctangents
(scripts/erfa_ieee.py, the series read from ERFA's nut00a.c and s06.c).
pyerfa (whose build may fuse a*b + c and uses the platform libm) is run on
every row as a cross-check within bounds derived from the arithmetic; a row
outside them, or too few rows compared, fails.

Usage (versions pinned in scripts/oracle-requirements.txt):
    .venv/bin/python -I scripts/gen_cio_golden.py <nut00a.c> <s06.c>           # write
    .venv/bin/python -I scripts/gen_cio_golden.py <nut00a.c> <s06.c> --check   # compare
"""

import hashlib
import pathlib
import sys

import erfa
import numpy

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import erfa_ieee as E  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "tests" / "golden" / "cio.csv"
ARGS_OUT = ROOT / "tests" / "golden" / "cio_args.csv"
PINS = {"pyerfa": "2.0.1.5", "numpy": "2.5.4"}
NUT00A_SHA256 = "a1538ec0277745db974ab76ca4b678a7602249bccecf9474e2b0268f9c2032ef"
S06_SHA256 = "6ad19dd59c3150d9f065b3f76d254c1cf3adb0cb6bacd6422c1dc6b6f14122ea"
EPS = 2.220446049250313e-16


def dates():
    """TT two-part dates 1800..2200 every 211 days plus a varying fraction,
    two dates of ERFA's test vectors, and both orders of the parts."""
    out = []
    k = 0
    day = -73050
    while day <= 73050:
        out.append((2451545.0, day + (k * 0.381966011250105) % 1.0))
        day += 211
        k += 1
    out += [(2400000.5, 53736.0), (2400000.5, 50123.9999), (53736.0, 2400000.5)]
    return out


class CrossCheck:
    def __init__(self):
        self.compared = 0

    def value(self, ours, theirs, tol, what):
        e = abs(ours - float(theirs))
        if e > tol:
            sys.exit(f"pyerfa {what}: {ours!r} vs {float(theirs)!r} ({e:e} > {tol:e})")
        self.compared += 1


def flat(m):
    return [float(v) for v in numpy.asarray(m).reshape(9)]


def transcription_check(cc, t, jd1, jd2):
    """The polynomials against pyerfa: within 8 ulp of the unreduced value."""
    at = abs(t)
    delaunay = (1.3e6 + 1.74e9 * at) * E.DAS2R
    planet = 7.0 + 8434.0 * at
    pairs = [(E.fal03(t), erfa.fal03(t), delaunay), (E.falp03(t), erfa.falp03(t), delaunay),
             (E.faf03(t), erfa.faf03(t), delaunay), (E.fad03(t), erfa.fad03(t), delaunay),
             (E.faom03(t), erfa.faom03(t), delaunay), (E.fame03(t), erfa.fame03(t), planet),
             (E.fave03(t), erfa.fave03(t), planet), (E.fae03(t), erfa.fae03(t), planet),
             (E.fama03(t), erfa.fama03(t), planet), (E.faju03(t), erfa.faju03(t), planet),
             (E.fasa03(t), erfa.fasa03(t), planet), (E.faur03(t), erfa.faur03(t), planet),
             (E.fapa03(t), erfa.fapa03(t), 0.03 * at), (E.obl06(t), erfa.obl06(jd1, jd2), 0.5)]
    pairs += list(zip(E.pfw06(t), erfa.pfw06(jd1, jd2), [0.03 * at + 1e-6, 0.5, 0.03 * at + 1e-6, 0.5]))
    for k, (mine, ref, mag) in enumerate(pairs):
        e = abs(mine - float(ref))
        e = min(e, E.D2PI - e)
        if e > 8 * EPS * mag:
            sys.exit(f"transcription {k} at t={t}: {mine!r} vs {float(ref)!r}")
        cc.compared += 1


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    got = {"pyerfa": erfa.__version__, "numpy": numpy.__version__}
    if got != PINS:
        sys.exit(f"tool versions {got} differ from the pins {PINS}")
    for path, pin in ((sys.argv[1], NUT00A_SHA256), (sys.argv[2], S06_SHA256)):
        digest = hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()
        if digest != pin:
            sys.exit(f"{path}: sha256 {digest} != pinned {pin}")
    E.load_series(sys.argv[1], sys.argv[2])
    cc = CrossCheck()
    lines = [
        "# generated by scripts/gen_cio_golden.py (ERFA 2.0.1 expressions in IEEE binary64, correctly rounded sines)",
        "jd1,jd2,dpsi00a,deps00a,dpsi06a,deps06a,gamb,phib,psib,epsa,s06,"
        + ",".join(f"pnm{i}" for i in range(9)) + ","
        + ",".join(f"c2i{i}" for i in range(9)) + ","
        + "era_jd2,xp,yp," + ",".join(f"c2t{i}" for i in range(9)),
    ]
    for k, (jd1, jd2) in enumerate(dates()):
        t = E.centuries(jd1, jd2)
        dp0, de0 = E.nut00a(jd1, jd2)
        dp6, de6 = E.nut06a(jd1, jd2)
        gamb, phib, psib, epsa = E.pfw06(t)
        pnm = E.pnm06a(jd1, jd2)
        x, y = pnm[2][0], pnm[2][1]
        s = E.s06(jd1, jd2, x, y)
        c2i = E.c2i06a(jd1, jd2)
        # UT1 = TT - 69.184 s; pole coordinates of the size of the real ones
        ut2 = jd2 - 69.184 / 86400.0
        xp = 1.5e-6 * E.sin_cr(0.3 * k)
        yp = 2.0e-6 * E.cos_cr(0.2 * k)
        c2t = E.c2t06a(jd1, jd2, jd1, ut2, xp, yp)
        # pyerfa within the bounds the crate's tests use (its sines are not
        # correctly rounded either; the Earth rotation angle's unreduced value
        # may round differently under a fused multiply-add)
        for ours, theirs, name in ((dp0, 0, "dpsi00a"), (de0, 1, "deps00a")):
            cc.value(ours, erfa.nut00a(jd1, jd2)[theirs], 2e-16, name)
        for ours, theirs, name in ((dp6, 0, "dpsi06a"), (de6, 1, "deps06a")):
            cc.value(ours, erfa.nut06a(jd1, jd2)[theirs], 2e-16, name)
        for ours, theirs in zip([v for row in pnm for v in row], flat(erfa.pnm06a(jd1, jd2))):
            cc.value(ours, theirs, 1e-15, "pnm06a")
        cc.value(s, erfa.s06(jd1, jd2, x, y), 1e-18, "s06")
        for ours, theirs in zip([v for row in c2i for v in row], flat(erfa.c2i06a(jd1, jd2))):
            cc.value(ours, theirs, 1e-15, "c2i06a")
        era_tol = 4 * EPS * E.D2PI * (2.0 + 0.00274 * abs(jd1 - E.DJ00 + ut2)) + 1e-15
        for ours, theirs in zip([v for row in c2t for v in row], flat(erfa.c2t06a(jd1, jd2, jd1, ut2, xp, yp))):
            cc.value(ours, theirs, era_tol, "c2t06a")
        vals = [jd1, jd2, dp0, de0, dp6, de6, gamb, phib, psib, epsa, s,
                *[v for row in pnm for v in row], *[v for row in c2i for v in row],
                ut2, xp, yp, *[v for row in c2t for v in row]]
        lines.append(",".join(repr(float(v)) for v in vals))
    args = [
        "# generated by scripts/gen_cio_golden.py: ERFA's argument and precession polynomials in IEEE operations",
        "jd1,jd2," + ",".join(f"ls{i}" for i in range(5)) + "," + ",".join(f"pl{i}" for i in range(13)) + ","
        + ",".join(f"s{i}" for i in range(8)) + ",gamb,phib,psib,epsa",
    ]
    for jd1, jd2 in dates():
        t = E.centuries(jd1, jd2)
        transcription_check(cc, t, jd1, jd2)
        ls, pl = E.nut00a_arguments(t)
        vals = [jd1, jd2, *ls, *pl, *E.s06_arguments(t), *E.pfw06(t)]
        args.append(",".join(repr(float(v)) for v in vals))
    # per date: 4 nutation angles, 3 matrices of 9, s, and 18 polynomials
    if cc.compared != 50 * len(dates()):
        sys.exit(f"the pyerfa cross-check compared {cc.compared} values, not {50 * len(dates())}")
    text = "\n".join(lines) + "\n"
    args_text = "\n".join(args) + "\n"
    if "--check" in sys.argv[3:]:
        for path, want in ((OUT, text), (ARGS_OUT, args_text)):
            if path.read_text(encoding="utf-8") != want:
                sys.exit(f"{path} differs from the regenerated table")
        print(f"{OUT.name}, {ARGS_OUT.name}: {len(lines) - 2} rows match ({cc.compared} pyerfa cross-checks)")
    else:
        OUT.write_text(text, encoding="utf-8")
        ARGS_OUT.write_text(args_text, encoding="utf-8")
        print(f"wrote {OUT.name}, {ARGS_OUT.name}: {len(lines) - 2} rows ({cc.compared} pyerfa cross-checks)")


if __name__ == "__main__":
    main()
