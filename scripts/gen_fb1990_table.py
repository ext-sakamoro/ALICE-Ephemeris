#!/usr/bin/env python3
"""Generate src/fb1990_table.rs from ERFA's dtdb.c.

The Fairhead & Bretagnon (1990) TDB-TT series (787 terms) is copied from
ERFA v2.0.1 `src/dtdb.c` (BSD-3-Clause, see THIRD-PARTY-NOTICES). The decimal literals are
copied character for character, so each Rust `f64` literal parses to the same
double as the C one.

Usage:
    python3 scripts/gen_fb1990_table.py <path to dtdb.c>          # write
    python3 scripts/gen_fb1990_table.py <path to dtdb.c> --check  # compare

Fetch the source with:
    curl -o dtdb.c https://raw.githubusercontent.com/liberfa/erfa/v2.0.1/src/dtdb.c
"""

import hashlib
import pathlib
import re
import sys

ERFA_TAG = "v2.0.1"
ERFA_COMMIT = "9915ba38c9365f8b0738269b8c2ac1fdd5f8dee3"
DTDB_SHA256 = "228bd7c7c1c88dda44c29a076f289c968f64d77a2dc389138b03ab5d1d442105"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "fb1990_table.rs"
TERMS = 787
# first index of each power-of-T block in ERFA's loops (T^0 .. T^4), and the end
BLOCKS = [0, 474, 679, 764, 784, 787]

ROW = re.compile(r"\{\s*([-+0-9.eE]+)\s*,\s*([-+0-9.eE]+)\s*,\s*([-+0-9.eE]+)\s*\}")


def render(src: bytes) -> str:
    digest = hashlib.sha256(src).hexdigest()
    if digest != DTDB_SHA256:
        sys.exit(f"dtdb.c sha256 {digest} != pinned {DTDB_SHA256}")
    text = src.decode("utf-8")
    start = text.index("fairhd[787][3] = {")
    end = text.index("};", start)
    rows = ROW.findall(text[start:end])
    if len(rows) != TERMS:
        sys.exit(f"found {len(rows)} rows, expected {TERMS}")
    out = [
        "// @generated by scripts/gen_fb1990_table.py — do not edit by hand.",
        "//",
        f"// Source: ERFA {ERFA_TAG} (commit {ERFA_COMMIT}) src/dtdb.c,",
        f"// sha256 {DTDB_SHA256}.",
        "// Copyright (C) 2013-2023, NumFOCUS Foundation. BSD-3-Clause; the licence",
        "// text is reproduced in THIRD-PARTY-NOTICES. The values are the Fairhead & Bretagnon",
        "// (1990) series as adapted in ERFA's eraDtdb.",
        "",
        "/// Number of terms of the series.",
        f"pub(crate) const TERMS: usize = {TERMS};",
        "",
        "/// First index of the T^0, T^1, T^2, T^3, T^4 blocks, then the end.",
        "pub(crate) const BLOCKS: [usize; 6] = [" + ", ".join(map(str, BLOCKS)) + "];",
        "",
        "/// `[amplitude (s), frequency (rad / Julian millennium), phase (rad)]`.",
        "#[rustfmt::skip]",
        "pub(crate) static FAIRHD: [[f64; 3]; TERMS] = [",
    ]
    for a, f, p in rows:
        out.append(f"    [{lit(a)}, {lit(f)}, {lit(p)}],")
    out.append("];")
    return "\n".join(out) + "\n"


def lit(s: str) -> str:
    # a C literal such as `0.0` or `1.5e-6` is a valid Rust f64 literal as long
    # as it has a digit before the point; `.5` never occurs in the table
    if s.startswith(".") or s.startswith("-."):
        sys.exit(f"unexpected literal {s}")
    if not any(c in s for c in ".eE"):
        s += ".0"
    return s


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    rendered = render(pathlib.Path(sys.argv[1]).read_bytes())
    if "--check" in sys.argv[2:]:
        current = OUT.read_text(encoding="utf-8")
        if current != rendered:
            sys.exit(f"{OUT} differs from the generator output")
        print(f"{OUT.name}: {TERMS} rows, identical")
    else:
        OUT.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"wrote {OUT} ({TERMS} rows)")


if __name__ == "__main__":
    main()
