//! The Laws of this crate and their semantics identifiers.
//!
//! Each conversion belongs to exactly one Law. A Law's `semantics_id` is the
//! SHA-256 of its name, its data (tables and constants, as their bit
//! patterns), the alice-det-math `SEMANTICS_ID` where it evaluates `f64`
//! transcendentals, and the digest of its outputs over a fixed grid of inputs
//! (`tests/law_ids.rs` recomputes all of them). A changed table, constant,
//! model or arithmetic therefore gives a different identifier, and a consumer
//! that records the identifier next to a value can tell which Law produced
//! it.

/// A Law: a name and a 32-byte semantics identifier.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Law {
    /// Stable name, `alice-ephemeris/<law>`.
    pub name: &'static str,
    /// SHA-256 semantics identifier.
    pub semantics_id: [u8; 32],
}

