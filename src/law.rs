/// Whether `stored` names `law`: its identifier, or an earlier one of [`PREVIOUS_SEMANTICS_IDS`].
#[must_use]
pub fn names_law(law: &Law, stored: &[u8; 32]) -> bool {
    law.semantics_id == *stored
        || PREVIOUS_SEMANTICS_IDS
            .iter()
            .any(|(name, id)| *name == law.name && id == stored)
}
