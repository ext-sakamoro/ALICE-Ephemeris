#!/usr/bin/env python3
"""Write src/star_table.rs and sky/stars.bin: the brightest stars of the HEASARC table `heasarc_bsc5p`, position, proper
motion and magnitude only, in the table's J2000 degrees and arcsec per year.

    python3 scripts/gen_star_table.py <heasarc_bsc5p.tdat> <how many> <retrieved YYYY-MM-DD> <out.rs> <out.bin>

The .bin is the same rows for a page to fetch once it is dark, so they are not in its first module. The catalogue
gives every value to a fixed number of decimals (ra and dec to 1e-4 degree, proper motion to 1e-3 arcsec a year,
magnitude to 1e-2), so the file holds those decimals as whole numbers, a column at a time, little endian:
ra as i32 (1e-4 degree), dec as i32 (1e-4 degree), pm_ra and pm_dec as i16 (1e-3 arcsec a year), mag as i16
(1e-2), each column `count` long, 14 bytes a star. Read back as (n / scale) * DEG (and ARCSEC), and the magnitude
as (n / 100) taken to f32, each is the same f64 / f32 as in the .rs, bit for bit: the run checks every value and
stops if one is not (`binary`), so the file never drifts from the table.

A row with no magnitude has nothing to draw. That leaves out the 14 objects that are not stars, which
have HR numbers and positions and no magnitude: the run checks all 14 are gone and that the table has
the number of rows it says. Anything else that does not read stops the run, and so do too few rows.

Author: Moroya Sakamoto
"""

import math
import re
import struct
import sys

SOURCE_URL = "https://heasarc.gsfc.nasa.gov/W3Browse/star-catalog/bsc5p.html"
IDENTIFIER = "ivo://nasa.heasarc/bsc5p"
LICENCE_URL = "https://www.usa.gov/government-works"
CITATION = "Hoffleit, D. and Warren, Jr., W.H., 1991, The Bright Star Catalog, 5th Revised Edition (Preliminary Version); table by the HEASARC"
# the HEASARC's list of objects with HR numbers that are not stars
NOT_STARS = {92, 95, 182, 1057, 1841, 2472, 2496, 3515, 3671, 6309, 6515, 7189, 7539, 8296}
ARCSEC = math.pi / 180 / 3600
DEG = math.pi / 180


def rows(text):
    """The table's rows as dicts, checked against its own count of rows"""
    fields, total, data = None, None, None
    lines = text.split("\n")
    for i, line in enumerate(lines):
        m = re.match(r"line\[1\]\s*=\s*(.*)", line)
        if m:
            fields = m.group(1).split()
        m = re.match(r"#\s*TOTAL ROWS:\s*(\d+)", line)
        if m:
            total = int(m.group(1))
        if line.strip() == "<DATA>":
            data = i + 1
            break
    if fields is None or total is None or data is None:
        raise ValueError("not a table: no fields, no count or no data")
    out = [dict(zip(fields, r.split("|"))) for r in lines[data:] if "|" in r]
    if len(out) != total:
        raise ValueError(f"{len(out)} rows, the table says {total}")
    return out


def star(row):
    """(ra, dec, pm_ra, pm_dec, mag): radians, radians per year; None when it has no magnitude"""
    if not row["vmag"].strip():
        return None
    pm = lambda name: float(row[name]) * ARCSEC if row[name].strip() else 0.0
    return (float(row["ra"]) * DEG, float(row["dec"]) * DEG, pm("pmra"), pm("pmdec"), float(row["vmag"]))


def brightest(table, count):
    kept = [(int(r["hr"]), star(r)) for r in table]
    left_out = {hr for hr, s in kept if s is None}
    if left_out != NOT_STARS:
        raise ValueError(f"rows with no magnitude are not the 14 that are not stars: {sorted(left_out ^ NOT_STARS)}")
    stars = [s for _, s in kept if s is not None]
    if count <= 0 or len(stars) < count:
        raise ValueError(f"{len(stars)} stars read, {count} asked for")
    # by magnitude, then position, so the same table always gives the same result
    return sorted(stars, key=lambda s: (s[4], s[0], s[1]))[:count]


def table(stars, retrieved):
    body = "".join(
        f"    Star {{ ra: {r!r}, dec: {d!r}, pm_ra: {a!r}, pm_dec: {b!r}, mag: {m!r} }},\n" for r, d, a, b, m in stars
    )
    return (
        "//! The brightest stars of the Bright Star Catalog. Generated by scripts/gen_star_table.py. Do not edit.\n"
        f"// Source: {SOURCE_URL} ({IDENTIFIER}), retrieved {retrieved}\n"
        f"// Licence: {LICENCE_URL}\n"
        f"// Citation: {CITATION}\n"
        "// Use of this data does not imply endorsement by NASA or the HEASARC.\n"
        "use crate::stars::Star;\n\n"
        "/// How many stars [`BRIGHTEST`] holds\n"
        f"pub const STAR_COUNT: usize = {len(stars)};\n\n"
        f"/// The {len(stars)} brightest stars: position, proper motion and magnitude\n"
        "#[rustfmt::skip]\n"
        "#[allow(clippy::approx_constant)] // catalogue values, one of which is near a constant\n"
        f"pub static BRIGHTEST: [Star; STAR_COUNT] = [\n{body}];\n"
    )


# the compact file: each column's whole-number unit (what the catalogue's decimals are), its range, its packing
COLUMNS = (("ra", DEG, 1e4, "i"), ("dec", DEG, 1e4, "i"), ("pm_ra", ARCSEC, 1e3, "h"), ("pm_dec", ARCSEC, 1e3, "h"))
RANGE = {"i": (-(2**31), 2**31 - 1), "h": (-(2**15), 2**15 - 1)}


def f32(v):
    return struct.unpack("<f", struct.pack("<f", v))[0]


def whole(v, unit, scale, kind, what):
    """`v` as a whole number of the column's units, read back to the same bits; anything else stops the run"""
    n = round(v / unit * scale)
    lo, hi = RANGE[kind]
    if not lo <= n <= hi or (n / scale) * unit != v:
        raise ValueError(f"{what} {v!r} is not a whole number of 1/{scale:g} of its unit in range")
    return n


def binary(stars):
    out = []
    for c, (name, unit, scale, kind) in enumerate(COLUMNS):
        col = [whole(s[c], unit, scale, kind, name) for s in stars]
        out.append(struct.pack(f"<{len(col)}{kind}", *col))
    mags = []
    for s in stars:
        n = round(s[4] * 100)
        if not RANGE["h"][0] <= n <= RANGE["h"][1] or f32(n / 100) != f32(s[4]):
            raise ValueError(f"mag {s[4]!r} is not a whole number of hundredths")
        mags.append(n)
    out.append(struct.pack(f"<{len(mags)}h", *mags))
    return b"".join(out)


def read_binary(data, count):
    """The rows of a compact file of `count` stars, as `binary` wrote them (the reader the sky module implements)"""
    if len(data) != count * 14:
        raise ValueError(f"{len(data)} bytes are not {count} stars of 14")
    at, cols = 0, []
    for name, unit, scale, kind in COLUMNS:
        size = 4 if kind == "i" else 2
        col = struct.unpack_from(f"<{count}{kind}", data, at)
        at += size * count
        cols.append([(n / scale) * unit for n in col])
    mags = [f32(n / 100) for n in struct.unpack_from(f"<{count}h", data, at)]
    return [(cols[0][i], cols[1][i], cols[2][i], cols[3][i], mags[i]) for i in range(count)]


def main(argv):
    if len(argv) != 5:
        print(__doc__, file=sys.stderr)
        return 2
    path, count, retrieved, out, out_bin = argv
    if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", retrieved):
        print("a table must say when it was retrieved", file=sys.stderr)
        return 2
    with open(path, encoding="latin-1") as f:
        stars = brightest(rows(f.read()), int(count))
    with open(out, "w", encoding="utf-8") as f:
        f.write(table(stars, retrieved))
    with open(out_bin, "wb") as f:
        f.write(binary(stars))
    print(f"wrote {len(stars)} stars to {out} and {out_bin}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
