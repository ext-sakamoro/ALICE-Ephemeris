//! The Laws of this crate and their semantics identifiers.
//!
//! Each conversion belongs to exactly one Law. A Law's `semantics_id` is the
//! SHA-256 of its name, its data (tables and constants, as their bit
//! patterns), [`DET_MATH_PINS`] where it evaluates `f64` transcendentals, and
//! the digest of its outputs over a frozen reference grid of inputs
//! (`tests/law_ids.rs` recomputes all of them). A function of alice-det-math
//! this crate does not call moves nothing; one it calls stops the compile.
//!
//! **The identifier moves if and only if the Law's inputs or its outputs on
//! the reference grid move.** The reference grids are pinned by their own
//! input hash, so they change only together with a change of meaning; the
//! regression tests use separate grids that are not part of any identifier
//! and may grow without moving it. A value recorded with its identifier says
//! which Law produced it.

