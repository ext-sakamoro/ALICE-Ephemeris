#!/usr/bin/env python3
"""Generate src/iau2006_table.rs from ERFA's nut00a.c and s06.c.

The IAU 2000A nutation series (678 luni-solar and 687 planetary terms) and the
series of the CIO locator s (IAU 2006, 66 terms) are copied from ERFA v2.0.1
`src/nut00a.c` and `src/s06.c` (BSD-3-Clause, see THIRD-PARTY-NOTICES). The
decimal literals are copied character for character, so each Rust literal
parses to the same double as the C one.

Usage:
    python3 scripts/gen_iau2006_tables.py <nut00a.c> <s06.c>          # write
    python3 scripts/gen_iau2006_tables.py <nut00a.c> <s06.c> --check  # compare

Fetch the sources with:
    curl -O https://raw.githubusercontent.com/liberfa/erfa/v2.0.1/src/nut00a.c
    curl -O https://raw.githubusercontent.com/liberfa/erfa/v2.0.1/src/s06.c
"""

import hashlib
import pathlib
import re
import sys

ERFA_TAG = "v2.0.1"
ERFA_COMMIT = "9915ba38c9365f8b0738269b8c2ac1fdd5f8dee3"
NUT00A_SHA256 = "a1538ec0277745db974ab76ca4b678a7602249bccecf9474e2b0268f9c2032ef"
S06_SHA256 = "6ad19dd59c3150d9f065b3f76d254c1cf3adb0cb6bacd6422c1dc6b6f14122ea"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "iau2006_table.rs"
COUNTS = {"xls": 678, "xpl": 687, "s0": 33, "s1": 3, "s2": 25, "s3": 4, "s4": 1}


def source(path: str, pin: str) -> str:
    data = pathlib.Path(path).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != pin:
        sys.exit(f"{path}: sha256 {digest} != pinned {pin}")
    return data.decode("utf-8")


def block(text: str, opener: str) -> str:
    start = text.index(opener)
    return text[start + len(opener):text.index("};", start)]


def lit(s: str) -> str:
    s = s.strip()
    if s.startswith(".") or s.startswith("-."):
        sys.exit(f"unexpected literal {s}")
    if not any(c in s for c in ".eE"):
        s += ".0"
    return s


def ints(fields) -> str:
    return "[" + ", ".join(str(int(f)) for f in fields) + "]"


def render(nut00a: str, s06: str) -> str:
    xls = re.findall(r"\{([^{}]*)\}", block(nut00a, "} xls[] = {"))
    xpl = re.findall(r"\{([^{}]*)\}", block(nut00a, "} xpl[] = {"))
    sp = re.findall(r"[-+0-9.]+e-6", block(s06, "static const double sp[] = {"))
    series = {
        n: re.findall(r"\{\{([^}]*)\},\s*([^,}]+),\s*([^}]+)\}", block(s06, f"static const TERM {n}[] = {{"))
        for n in ("s0", "s1", "s2", "s3", "s4")
    }
    found = {"xls": len(xls), "xpl": len(xpl), **{n: len(v) for n, v in series.items()}}
    if found != COUNTS or len(sp) != 6:
        sys.exit(f"found {found} and {len(sp)} polynomial terms, expected {COUNTS} and 6")
    out = [
        "// @generated by scripts/gen_iau2006_tables.py — do not edit by hand.",
        "//",
        f"// Source: ERFA {ERFA_TAG} (commit {ERFA_COMMIT}) src/nut00a.c",
        f"// (sha256 {NUT00A_SHA256}) and src/s06.c",
        f"// (sha256 {S06_SHA256}).",
        "// Copyright (C) 2013-2023, NumFOCUS Foundation. BSD-3-Clause; the licence",
        "// text is reproduced in THIRD-PARTY-NOTICES. The values are the IAU 2000A",
        "// nutation series (Mathews, Herring & Buffett 2002) and the series of the CIO",
        "// locator s compatible with IAU 2006 precession, as in ERFA's eraNut00a and eraS06.",
        "",
        "/// Luni-solar nutation: multipliers of l, l′, F, D, Ω, then longitude sin, t·sin,",
        "/// cos and obliquity cos, t·cos, sin coefficients (0.1 µas).",
        "#[rustfmt::skip]",
        f"pub(crate) static NUT_LUNI_SOLAR: [([i8; 5], [f64; 6]); {COUNTS['xls']}] = [",
    ]
    for row in xls:
        f = [x for x in row.replace("\n", " ").split(",") if x.strip()]
        out.append(f"    ({ints(f[:5])}, [{', '.join(lit(x) for x in f[5:])}]),")
    out += [
        "];",
        "",
        "/// Planetary nutation: multipliers of l, F, D, Ω, the longitudes of Mercury to",
        "/// Neptune and the general precession, then longitude sin, cos and obliquity sin,",
        "/// cos coefficients (0.1 µas).",
        "#[rustfmt::skip]",
        f"pub(crate) static NUT_PLANETARY: [([i8; 14], [i32; 4]); {COUNTS['xpl']}] = [",
    ]
    for row in xpl:
        f = [x for x in row.split(",") if x.strip()]
        out.append(f"    ({ints(f[:14])}, {ints(f[14:])}),")
    out += [
        "];",
        "",
        "/// Polynomial part of s + XY/2 (arcseconds, powers 0 to 5 of t).",
        "pub(crate) static S06_POLYNOMIAL: [f64; 6] = [" + ", ".join(lit(x) for x in sp) + "];",
    ]
    for n, rows in series.items():
        power = n[1]
        out += [
            "",
            f"/// Terms of s + XY/2 multiplied by t^{power}: multipliers of l, l′, F, D, Ω, LVe,",
            "/// LE, pA, then sine and cosine coefficients (arcseconds).",
            "#[rustfmt::skip]",
            f"pub(crate) static S06_T{power}: [([i8; 8], f64, f64); {len(rows)}] = [",
        ]
        for nfa, s, c in rows:
            out.append(f"    ({ints(nfa.split(','))}, {lit(s)}, {lit(c)}),")
        out.append("];")
    return "\n".join(out) + "\n"


def main() -> None:
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    rendered = render(source(sys.argv[1], NUT00A_SHA256), source(sys.argv[2], S06_SHA256))
    if "--check" in sys.argv[3:]:
        if OUT.read_text(encoding="utf-8") != rendered:
            sys.exit(f"{OUT} differs from the generator output")
        print(f"{OUT.name}: identical")
    else:
        OUT.write_text(rendered, encoding="utf-8", newline="\n")
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
